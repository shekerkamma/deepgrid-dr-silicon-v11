/** Keep a number with its unit on one line ("114 MHz", "2 A", "64 KB"), as the rest of the site's copy does. */
const UNIT = /(\d) (?=(?:MHz|kHz|GHz|Gbps|Mbps|kSPS|MSPS|KB|MB|GB|TOPS|mA|µA|µs|ns|ms|µW|mV|kV|dBm|dB|ppm|°C|bit|V|A|s|cycles|pages|keys|lanes|channels|outputs|columns|zones|nodes|domains)\b)/g;
export const nbspUnits = (s: string) => s.replace(UNIT, '$1\u00a0');

/** A native architecture diagram, rendered in the site's own design: rows of zones of blocks, with the
 *  numbered markers of the reading path on the blocks they refer to. Generated by scripts/sku-diagrams/. */
