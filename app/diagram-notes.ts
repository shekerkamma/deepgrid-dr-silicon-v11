export type NativeZone = {k?: string; name: string; cols: number; mcols?: number; w: number; tone?: 'safe' | 'optional'; note?: string; blocks: (NativeBlock | null)[]};
export type NativeRow = {bus: string; k?: string} | {zones: NativeZone[]};
export type NativeDiagramData = {frame: string; rows: NativeRow[]; edges?: {a: string; b: string; m?: string; d?: string}[]; input?: string; output?: string; banner?: string; strip?: string[]};

