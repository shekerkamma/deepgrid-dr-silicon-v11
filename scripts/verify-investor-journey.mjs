import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const base=process.argv[2]?.replace(/\/?$/, '/');
if(!base) throw new Error('Pass the built site base URL');
const out=process.argv[3]||'verify-shots/investor';fs.mkdirSync(out,{recursive:true});
const axe=createRequire(import.meta.url).resolve('axe-core/axe.min.js');
const browser=await chromium.launch();
for(const width of [1440,768,390]){
  const context=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.url().startsWith(base)&&r.status()>=400)errors.push(`HTTP ${r.status()} ${r.url()}`);});
  const inspect=async(name)=>{
    await page.evaluate(()=>document.fonts.ready);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,name+' horizontal overflow');
    await page.addScriptTag({path:axe});
    const violations=await page.evaluate(async()=> (await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21a','wcag21aa']}})).violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)})));
    assert.deepEqual(violations,[],name+' accessibility');
    await page.screenshot({path:`${out}/${name}-${width}.png`});
  };
  await page.goto(base,{waitUntil:'networkidle'});
  assert.equal(await page.locator('.ij-review-paths a').count(),3);
  const primary=page.locator('.v11-hero .v11-button');
  assert.match(await primary.innerText(),/Request a discussion/);
  const box=await primary.boundingBox();
  assert.ok(box&&box.y>=0&&box.y+box.height<=900,'Primary discussion action visible in first viewport');
  await inspect('home');
  await page.locator('.v11-hero-copy a').filter({hasText:'Read the investment brief'}).click();
  await page.getByRole('tab',{name:'Tranche 1 brief'}).waitFor();
  await inspect('brief');
  await page.locator('.ij-discussion a').click();
  await page.getByRole('button',{name:'Investment & data room',exact:true}).waitFor();
  // Pages serves HTML before the contact handlers load; let its route assets settle before submitting.
  await page.waitForLoadState('networkidle');
  assert.equal(new URL(page.url()).searchParams.get('intent'),'investor');
  assert.equal(await page.getByLabel('Voltage range',{exact:true}).count(),0);
  await page.getByRole('button',{name:'Compose discussion request',exact:true}).click();
  assert.equal(await page.evaluate(()=>document.activeElement?.id),'enq-name');
  await page.getByLabel('Full name').fill('Review visitor');
  await page.getByLabel(/^Email/).fill('review@example.com');
  await page.getByLabel('Company or organization').fill('Review organization');
  await page.getByLabel('What would you like to discuss?').fill('Please share the funding assumptions and diligence material.');
  await inspect('investor-contact');
  await page.getByRole('button',{name:'Engineering evaluation',exact:true}).click();
  assert.equal(new URL(page.url()).searchParams.get('intent'),'engineering');
  assert.equal(await page.getByLabel('Voltage range',{exact:true}).count(),1);
  assert.equal(await page.getByLabel('Application description').inputValue(),'Please share the funding assumptions and diligence material.');
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.getByRole('button',{name:'Engineering evaluation',exact:true}).getAttribute('aria-pressed'),'true');
  await inspect('engineering-contact');
  await page.goto(base+'portfolio/brief?view=use-cases&sku=SKU-6&q=radar&market=later',{waitUntil:'networkidle'});
  await page.getByRole('searchbox',{name:'Find a use case'}).waitFor();
  assert.equal(await page.getByRole('searchbox',{name:'Find a use case'}).inputValue(),'radar');
  assert.equal(await page.locator('.uc-case').count(),1);
  await page.getByRole('searchbox',{name:'Find a use case'}).fill('all');
  assert.equal(new URL(page.url()).searchParams.get('q'),'all');
  await page.reload({waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.querySelector('.uc-filters input')?.value==='all');
  assert.equal(await page.getByRole('searchbox',{name:'Find a use case'}).inputValue(),'all');
  await page.getByRole('searchbox',{name:'Find a use case'}).fill('radar');
  assert.match(await page.locator('.uc-selection-note').innerText(),/outside/);
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await page.getByRole('combobox',{name:'Show'}).inputValue(),'later');
  await page.locator('.uc-case').click();
  await page.locator('.uc-detail-actions a').filter({hasText:'Discuss this opportunity'}).click();
  await page.getByRole('button',{name:'Strategic partnership',exact:true}).waitFor();
  await page.waitForFunction(()=>[...document.querySelectorAll('.ij-contact-intents button')].some(button=>button.textContent==='Strategic partnership'&&button.getAttribute('aria-pressed')==='true'));
  assert.equal(await page.getByRole('button',{name:'Strategic partnership',exact:true}).getAttribute('aria-pressed'),'true');
  assert.match(await page.getByLabel('What would you like to discuss?').inputValue(),/SKU-7/);
  await inspect('partner-contact');
  assert.deepEqual(errors,[],`${width} runtime or asset errors`);
  console.log(`PASS ${width}: investor journey, validation focus, engineering path, intent reload, shareable filters, chip partnership context and accessibility`);
  await context.close();
}
await browser.close();
